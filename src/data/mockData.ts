export const sanitizeImageUrl = (url?: string): string => {
  if (!url) return PHONE_IMAGE;
  if (url.startsWith('data:image/')) return url;
  for (const [key, assetUrl] of Object.entries(IMAGE_MAP)) {
    if (url.includes(key)) {
      return assetUrl;
    }
  }
  if (url.startsWith('/src/assets/images/')) {
    return PHONE_IMAGE;
  }
  return url;
};

